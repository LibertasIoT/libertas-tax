pub(crate) fn countries() -> Vec<RecordChoice> {
    COUNTRIES
        .iter()
        .map(|(id, key)| RecordChoice {
            id: *id,
            label: crate::Message::new(*key, alloc::vec![]).encode(),
        })
        .collect()
}
pub(crate) fn rule(
    account: bool,
    required: Option<bool>,
    countries: &[i64],
) -> Option<&'static str> {
    issue(account, required, countries).map(|issue| issue.key)
}

pub(crate) fn issue(
    account: bool,
    required: Option<bool>,
    countries: &[i64],
) -> Option<crate::validation::ValidationIssue> {
    use crate::validation::ValidationIssue;
    if account != required.is_some() {
        return Some(ValidationIssue::new("FBAR_ANSWER_NEEDED").at_field("fbar_required"));
    }
    if (required == Some(true)) == countries.is_empty() {
        return Some(ValidationIssue::new("FBAR_COUNTRIES_NEEDED").at_field("fbar_countries"));
    }
    if let Some(index) =
        countries.iter().enumerate().position(|(i, id)| countries[..i].contains(id))
    {
        return Some(
            ValidationIssue::new("FBAR_COUNTRY_TWICE").at_list_item("fbar_countries", index),
        );
    }
    if let Some(index) =
        countries.iter().position(|id| !COUNTRIES.iter().any(|(known, _)| known == id))
    {
        return Some(
            ValidationIssue::new("FBAR_COUNTRY_NOT_LISTED").at_list_item("fbar_countries", index),
        );
    }
    None
}

pub(crate) fn country_key(id: i64) -> Option<&'static str> {
    COUNTRIES.iter().find(|(known, _)| *known == id).map(|(_, key)| *key)
}
