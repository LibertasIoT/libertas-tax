#!/usr/bin/env python3
"""Extract current IRS Pub. 590-B Appendix B tables I/II/III from saved HTML.
Usage: python3 tools/extract-rmd-tables.py /path/to/p590b.html
Source: https://www.irs.gov/publications/p590b (2025 edition).
No network or third-party Python dependencies; validates published examples,
complete coverage and symmetric joint-table cells before writing Rust constants.
"""
from pathlib import Path
from decimal import Decimal
import hashlib
import html
import re
import sys

raw = Path(sys.argv[1]).read_bytes()
uniform, joint, single = {}, {}, {}
for table in re.findall(r'<table\b.*?</table>', raw.decode(), re.S):
    text = html.unescape(re.sub('<[^>]*>', '', table))
    is_single = 'Single Life Expectancy' in text
    is_joint = 'Joint and Last Survivor Life Expectancy' in text
    is_uniform = 'Uniform Lifetime' in text
    if not (is_joint or is_uniform or is_single):
        continue
    columns = None
    for row in re.findall(r'<tr\b.*?</tr>', table, re.S):
        cells = [re.sub(r'\s+', ' ', html.unescape(re.sub('<[^>]*>', '', c))).strip()
                 for c in re.findall(r'<t[dh]\b[^>]*>(.*?)</t[dh]>', row, re.S)]
        if is_joint and cells and cells[0] == 'Ages':
            columns = [int(c.rstrip('+')) for c in cells[1:]]
        elif is_joint and columns and cells and re.fullmatch(r'\d+\+?', cells[0]):
            age = int(cells[0].rstrip('+'))
            assert len(cells) == len(columns) + 1
            for col, cell in zip(columns, cells[1:]):
                value = int(Decimal(cell) * 10)
                assert (age, col) not in joint
                joint[age, col] = value
        elif (is_uniform or is_single) and len(cells) == 4 and cells[0].isdigit():
            for age, value in zip(cells[::2], cells[1::2]):
                if age:
                    age = int(age.replace(' and over', '').rstrip('+'))
                    target = single if is_single else uniform
                    assert age not in target
                    target[age] = int(Decimal(value) * 10)
assert set(single) == set(range(121))
assert single[0] == 846 and single[57] == 298 and single[120] == 10
assert set(uniform) == set(range(72, 121))
# The publication lays out a symmetric table in blocks, omitting repeated blocks.
for (age, other), value in list(joint.items()):
    assert joint.get((other, age), value) == value
    joint[other, age] = value
assert len(joint) == 101 * 101
assert uniform[73] == 265 and uniform[75] == 246 and uniform[120] == 20
assert joint[75, 64] == 253 and joint[120, 120] == 10
out = [
    '// Generated by tools/extract-rmd-tables.py from IRS Pub. 590-B (2025).',
    '// Source: https://www.irs.gov/publications/p590b',
    '// HTML SHA-256: ' + hashlib.sha256(raw).hexdigest(),
    '// Values are tenths of years. Last age is 120 and over.',
    '#[rustfmt::skip]',
    'pub(crate) const SINGLE: [i64; 121] = [' + ', '.join(str(single[a]) for a in range(121)) + '];',
    '#[rustfmt::skip]',
    'pub(crate) const UNIFORM: [i64; 49] = [' + ', '.join(str(uniform[a]) for a in range(72, 121)) + '];',
    '// Joint rows: owner ages 73..120; columns: spouse ages 20..120.',
    '#[rustfmt::skip]',
    'pub(crate) static JOINT: [[i64; 101]; 48] = [',
]
for age in range(73, 121):
    out.append('    [' + ', '.join(str(joint[age, other]) for other in range(20, 121)) + '],')
out.append('];\n')
Path(__file__).resolve().parents[1].joinpath('src/retirement/rmd_tables.rs').write_text('\n'.join(out))
print('Verified 121 single-life and 49 uniform factors and 10,201 joint cells; emitted applicable owner rows.')
