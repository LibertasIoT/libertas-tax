#!/usr/bin/env python3
"""Extract equipment percentages from IRS Publication 946 (2025), Appendix A.
Usage: python3 tools/extract-macrs-tables.py /path/to/p946.pdf
Requires pdftotext. Output is src/kernel/cost_recovery/macrs_tables.rs; no network access is used.
"""
from pathlib import Path
from decimal import Decimal
import hashlib
import re
import subprocess
import sys

pdf = Path(sys.argv[1])
text = subprocess.check_output(['pdftotext', '-layout', str(pdf), '-'], text=True)
classes = [3, 5, 7, 10, 15, 20]
wanted = set(range(1, 6)) | set(range(8, 13)) | set(range(14, 19))
values = {}
table = None
columns = None
anchors = None
for line in text.splitlines():
    match = re.search(r'Table A-(\d+)(?:\.|\s)', line)
    if match:
        table = int(match[1])
        columns = anchors = None
        continue
    if table not in wanted:
        continue
    if re.search(r'3-year\s+5-year', line):
        columns = classes
        continue
    tokens = line.split()
    if tokens[:3] in [['2.5', '3', '3.5'], ['10', '10.5', '11'], ['18', '19', '20']]:
        columns = [Decimal(t) for t in tokens]
        continue
    if columns is None:
        continue
    row = re.match(r'\s*(\d+)\s+', line)
    if not row:
        continue
    year = int(row[1])
    cells = list(re.finditer(r'\d+\.\d+%?', line[row.end():]))
    if not cells:
        continue
    positions = [row.end() + (m.start() + m.end()) / 2 for m in cells]
    if year == 1:
        assert len(cells) == len(columns), (table, line)
        anchors = positions
    assert anchors is not None, (table, line)
    used = set()
    for cell, position in zip(cells, positions):
        index = min(range(len(anchors)), key=lambda i: abs(position - anchors[i]))
        assert index not in used and abs(position - anchors[index]) < 4, (table, year, line)
        used.add(index)
        life = columns[index]
        if life not in classes:
            continue
        key = (table, int(life), year)
        assert key not in values, key
        values[key] = int(Decimal(cell[0].rstrip('%')) * 1000)

rows = []
for tables in [range(1, 6), range(14, 19), range(8, 13)]:
    for table in tables:
        for life in classes:
            row = [values[(table, life, year)] for year in range(1, life + 2)]
            assert sum(row) == 100000, (table, life, sum(row))
            rows.append((table, life, row))

out = ['// Generated by tools/extract-macrs-tables.py from IRS Publication 946 (2025).',
       '// Source: https://www.irs.gov/pub/irs-pdf/p946.pdf',
       '// PDF SHA-256: ' + hashlib.sha256(pdf.read_bytes()).hexdigest(),
       '// Each integer is one thousandth of a percentage point; divisor = 100,000.',
       '// Order: ordinary GDS / 150% DB / straight line; HY / Q1 / Q2 / Q3 / Q4;',
       '// then recovery class 3 / 5 / 7 / 10 / 15 / 20. Preserve published rounding.',
       'pub(crate) const RATES: [&[i64]; 90] = [']
for table, life, row in rows:
    out.append(f'    // Table A-{table}, {life}-year property.')
    out.append('    &[' + ', '.join(map(str, row)) + '],')
out.append('];\n')
Path('src/kernel/cost_recovery/macrs_tables.rs').write_text('\n'.join(out))
subprocess.run(['rustfmt', 'src/kernel/cost_recovery/macrs_tables.rs'], check=True)
print(f'Extracted {len(rows)} schedules, {sum(len(row) for _, _, row in rows)} rates.')
